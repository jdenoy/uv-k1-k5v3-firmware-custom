/*
 * ToneCall - overlay app: sends a sequential tone call (ZVEI-1, ZVEI-2, CCIR-1,
 * CCIR-2) chosen among the user's presets, on demand, on the current channel.
 *
 * The presets live in this app's mutable asset block (../tonecall_presets.h),
 * written by the companion editor ToneCall Edit. Nothing is built in.
 *
 * A call keys up with the channel's TX settings (CTCSS/DCS included), leaves
 * TC_PRELOAD_MS of carrier, sends the tones back to back and unkeys, through
 * the existing API only. The app then stays in RX with the speaker following
 * the squelch, so the station's acknowledgement is heard; EXIT returns to the
 * channel, where the conversation goes on with the PTT (no code is ever sent
 * with the PTT).
 *
 * Keys: UP/DOWN select · MENU or PTT send · EXIT quit (from the listen screen:
 *       MENU/PTT sends again, UP/DOWN back to the list).
 */

#include <stdint.h>
#include <stdbool.h>
#include "../app_api.h"
#include "../tonecall_presets.h"
#include "tonecall_seq.h"
#include "tonecall_assets.h"   /* generated by gen_assets.py */

#ifndef APP_VERSION
#define APP_VERSION "dev"
#endif

#define LOOP_MS        10u
#define ROWS           5u      /* presets shown at once, lines 1-5 */
#define CFG_MAGIC      0x7Cu
#define TC_PRELOAD_MS  300u    /* carrier (+ CTCSS) before the first tone */

/* BK4819/BK4829 registers, values as the resident tone path writes them. */
#define REG_0C         0x0Cu   /* bit 1: squelch open */
#define REG_30         0x30u
#define REG_70         0x70u
#define REG_30_TX_LINK 0xC3FAu /* BK4819_EnableTXLink                      */
#define REG_30_IDLE    0xC1FEu /* as BK4819_PlaySingleTone leaves it       */
#define REG_70_TONE1   0xC200u /* TONE1 on, tuning gain 66 (as 1750 Hz)    */

enum { SCREEN_LIST = 0, SCREEN_LISTEN };

static struct {
    const app_api_t *A;
    uint8_t sel, top, screen, held;
    bool running, dirty, sentOk, sqlOpen;
    char name[TC_NAME_MAX + 1u];
    char code[TC_MAX_DIGITS + 1u];
    uint8_t type;
} g;
#define A (g.A)

static const uint32_t PLACE[9] = {
    100000000u, 10000000u, 1000000u, 100000u, 10000u, 1000u, 100u, 10u, 1u
};

/* ---- tiny formatting (no division linked) ---- */
static uint8_t slen(const char *s){ uint8_t n=0; while(s[n]) n++; return n; }
static char *put(char *o, const char *s){ while(*s) *o++=*s++; return o; }
static char *putu(char *o, uint32_t v){
    bool lead=true;
    for(uint8_t i=0;i<9u;i++){
        uint8_t d=0;
        while(v>=PLACE[i]){ v-=PLACE[i]; d++; }
        if(d||i==8u) lead=false;
        if(!lead) *o++=(char)('0'+d);
    }
    return o;
}

/* ---- presets ---- */
/* Load preset i into g.name / g.code / g.type; false if it is empty. */
static bool loadPreset(uint8_t i){
    uint8_t r[TC_REC_LEN];
    A->asset_read((uint16_t)(F_PRESETS+4u+i*TC_REC_LEN),r,TC_REC_LEN);
    uint8_t n=TC_NAME_MAX;
    while(n && r[TC_REC_NAME+n-1u]==' ') n--;
    for(uint8_t k=0;k<n;k++) g.name[k]=(char)r[TC_REC_NAME+k];
    g.name[n]='\0';
    const uint8_t fmt=r[TC_REC_FORMAT];
    uint8_t len=(uint8_t)(fmt>>4);
    g.type=(uint8_t)(fmt&15u);
    if(len>TC_MAX_DIGITS||g.type>=TC_TYPE_COUNT) len=0;
    for(uint8_t k=0;k<len;k++){
        const uint8_t b=r[TC_REC_CODE+(k>>1)];
        const uint8_t d=(uint8_t)((k&1u)?(b&15u):(b>>4));
        if(d>9u){ len=0; break; }
        g.code[k]=(char)('0'+d);
    }
    g.code[len]='\0';
    return len!=0;
}

static bool presetsOk(void){
    uint32_t magic;
    A->asset_read(F_PRESETS,&magic,4u);
    return magic==TC_PRESETS_MAGIC;
}

/* ---- the channel's TX tone ---- */
/* "CT123.0", "D023N" or "D023I" from the TX VFO (beam_get, Labs builds), in
 * s; false when the channel has none or the service is absent. */
static bool txTone(char *s){
    app_beam_channel_t ch;
    if(!A->beam_get) return false;
    A->beam_get(&ch);
    char *o=s;
    if(ch.tx_codetype==1u && ch.tx_code<CTCSS_COUNT){          /* CTCSS, Hz x 10 */
        uint16_t v;
        A->asset_read((uint16_t)(CTCSS+ch.tx_code*2u),&v,2u);
        *o++='C'; *o++='T';
        char *e=putu(o,v);
        e[1]='\0'; e[0]=e[-1]; e[-1]='.';
        return true;
    }
    if((ch.tx_codetype==2u||ch.tx_codetype==3u) && ch.tx_code<DCS_COUNT){   /* DCS N / I */
        uint8_t low;
        A->asset_read((uint16_t)(DCS_LOW+ch.tx_code),&low,1u);
        const uint16_t v=(uint16_t)(low|(ch.tx_code>=64u?0x100u:0u));
        *o++='D';
        *o++=(char)('0'+((v>>6)&7u)); *o++=(char)('0'+((v>>3)&7u)); *o++=(char)('0'+(v&7u));
        *o++=ch.tx_codetype==2u?'N':'I'; *o='\0';
        return true;
    }
    return false;
}

/* ---- drawing ---- */
static void invertLine(uint8_t line){ for(uint8_t x=0;x<128u;x++) A->fb[line][x]^=0xFFu; }

/* "1 NAME" left, the code right: the row of preset i on a frame line. */
static void drawRow(uint8_t i, uint8_t line){
    char s[TC_NAME_MAX+3u];
    const bool used=loadPreset(i);
    char *o=s; *o++=(char)('1'+i); *o++=' ';
    o=put(o,used?(g.name[0]?g.name:"-"):"EMPTY"); *o='\0';
    A->print_normal(s,1u,0u,line);
    if(used) A->print_normal(g.code,(uint8_t)(127u-slen(g.code)*7u),0u,line);
}

static void chrome(const char *title){
    char s[16];
    A->display_clear();
    A->status_clear();
    A->print_inverse(title,2u,0u,true,true,(uint8_t)(2u+slen(title)*4u));
    A->print_tiny(APP_VERSION,(uint8_t)(6u+slen(title)*4u),1u,true,false);
    A->draw_battery();
    /* the TX frequency (10 Hz units) as MHz with 5 decimals */
    { char *e=putu(s,A->tx_freq());
      e[1]='\0';
      for(uint8_t k=0;k<5u;k++,e--) e[0]=e[-1];
      e[0]='.'; }
    A->print_normal(s,1u,0u,0u);
    /* the channel's TX tone, when there is one, right-aligned */
    if(txTone(s)) A->print_normal(s,(uint8_t)(127u-slen(s)*7u),0u,0u);
}

static void drawList(void){
    chrome("TONECALL");
    if(!presetsOk()){
        A->print_normal("NO PRESETS",0u,127u,2u);
        A->print_normal("REINSTALL APP",0u,127u,3u);
        return;
    }
    for(uint8_t r=0;r<ROWS;r++){
        const uint8_t i=(uint8_t)(g.top+r);
        drawRow(i,(uint8_t)(1u+r));
        if(i==g.sel) invertLine((uint8_t)(1u+r));
    }
    if(loadPreset(g.sel)) A->print_tiny(tcTypeNames[g.type],1u,50u,false,false);
    A->print_tiny("M/PTT SEND",87u,50u,false,false);
}

static void drawListen(void){
    chrome("TONECALL");
    loadPreset(g.sel);
    A->print_string(g.name[0]?g.name:g.code,0u,127u,1u,8u);
    A->print_normal(g.sentOk?(g.sqlOpen?"RX":"LISTENING"):"TX OFF",0u,127u,4u);
    A->print_tiny(tcTypeNames[g.type],1u,50u,false,false);
    A->print_tiny(g.code,(uint8_t)(127u-slen(g.code)*4u),50u,false,false);
}

static void draw(void){
    if(g.screen==SCREEN_LISTEN) drawListen(); else drawList();
    A->blit_status(); A->blit_full();
}

/* ---- the call ---- */
/* Key up, TC_PRELOAD_MS of carrier, the tones back to back, unkey: the same
 * register sequence as the resident tone path (BK4819_PlaySingleTone), with
 * the channel's CTCSS/DCS left on by tx_set_params. */
static bool sendCall(void){
    uint16_t tones[TC_MAX_DIGITS];
    if(!loadPreset(g.sel)) return false;
    const uint8_t n=TC_BuildTones(g.type,g.code,tones);
    const uint16_t ms=TC_ToneMs(g.type);
    if(!n||A->tx_state()!=0) return false;

    A->tx_set_params();                 /* carrier + PA, channel CTCSS/DCS   */
    A->tx_mute(true);                   /* microphone path muted             */
    A->set_af(APP_AF_MUTE);
    A->bk_write(REG_70,REG_70_TONE1);
    A->bk_write(REG_30,REG_30_TX_LINK);
    A->led(true);
    A->delay_ms(TC_PRELOAD_MS);
    for(uint8_t k=0;k<n;k++) A->play_tone_raw(tones[k],ms);   /* unmute, tone, mute */
    A->bk_write(REG_70,0u);
    A->bk_write(REG_30,REG_30_IDLE);
    A->tx_mute(false);
    A->tx_end();                        /* PA off + RX registers restored     */
    A->led(false);
    return true;
}

static void startCall(void){
    g.sentOk=sendCall();
    g.screen=SCREEN_LISTEN;
    g.sqlOpen=false;
    if(g.sentOk) A->set_af(APP_AF_FM);
    g.dirty=true;
}

static void leaveListen(void){
    A->audio_path(false);
    A->set_af(APP_AF_MUTE);
    g.screen=SCREEN_LIST;
}

/* ---- keys ---- */
static void listKey(uint8_t key){
    const int8_t d=A->nav_dir(key);
    if(d>0) g.sel=(uint8_t)(g.sel+1u<TC_PRESET_COUNT?g.sel+1u:0u);
    else if(d<0) g.sel=(uint8_t)(g.sel?g.sel-1u:TC_PRESET_COUNT-1u);
    else if(key==APP_KEY_MENU||key==APP_KEY_PTT){ if(presetsOk()) startCall(); return; }
    else if(key==APP_KEY_EXIT){ g.running=false; return; }
    if(g.sel<g.top) g.top=g.sel;
    else if(g.sel>=g.top+ROWS) g.top=(uint8_t)(g.sel-ROWS+1u);
}

static void listenKey(uint8_t key){
    if(key==APP_KEY_MENU||key==APP_KEY_PTT){ startCall(); return; }
    leaveListen();
    if(key==APP_KEY_EXIT) g.running=false;
}

__attribute__((section(".text.entry"),used))
void app_main(const app_api_t *api){
    uint8_t cfg[2], saved;
    A=api;
    g.held=APP_KEY_INVALID;
    api->cfg_load(cfg,sizeof(cfg));
    if(cfg[0]==CFG_MAGIC && cfg[1]<TC_PRESET_COUNT) g.sel=cfg[1];
    saved=cfg[0]==CFG_MAGIC?g.sel:0xFFu;
    g.top=(uint8_t)(g.sel>=ROWS?g.sel-ROWS+1u:0u);
    g.running=true; g.dirty=true;
    api->backlight_on();

    while(g.running){
        if(g.screen==SCREEN_LISTEN && g.sentOk){
            /* speaker on while the squelch is open: the acknowledgement is heard */
            const bool open=(A->bk_read(REG_0C)&2u)!=0;
            A->audio_path(open);
            if(open!=g.sqlOpen){ g.sqlOpen=open; g.dirty=true; }
        }
        if(g.dirty){ g.dirty=false; draw(); }
        const uint8_t key=api->get_key();
        if(key==APP_KEY_SAVER||key==APP_KEY_WAKE){ g.held=APP_KEY_INVALID; g.dirty=true; }
        else if(key!=g.held){
            g.held=key;
            if(key!=APP_KEY_INVALID){
                api->backlight_on();
                if(g.screen==SCREEN_LISTEN) listenKey(key); else listKey(key);
                g.dirty=true;
            }
        }
        api->battery_sample(); api->delay_ms(LOOP_MS); api->backlight_update();
    }

    if(g.screen==SCREEN_LISTEN) leaveListen();
    if(g.sel!=saved){ cfg[0]=CFG_MAGIC; cfg[1]=g.sel; api->cfg_save(cfg,sizeof(cfg)); }   /* flash written only on change */
}
