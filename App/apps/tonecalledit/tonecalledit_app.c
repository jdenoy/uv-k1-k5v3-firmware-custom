/*
 * ToneCall Edit - companion editor for ToneCall's presets.
 *
 * ToneCall's own config area is too small for named presets (16 bytes), so
 * the presets are a block of ToneCall's assets that this app rewrites through
 * the configuration proxy (../tonecall_presets.h): cfg_load reads the block,
 * cfg_save stages it, and the loader writes it into ToneCall when this app
 * exits. Same split as APRS TX / APRS Edit.
 *
 * Index: UP/DOWN select · MENU edit · F clear · EXIT save and quit.
 * Editor: UP/DOWN field · MENU keep · EXIT discard.
 *   NAME  number keys type letters (multi-tap), * ABC/123, F delete
 *   TYPE  * next type, keys 1-4 pick ZVEI-1 / ZVEI-2 / CCIR-1 / CCIR-2
 *   CODE  number keys add a digit (up to 8), F delete
 */

#include <stdint.h>
#include <stdbool.h>
#include <stddef.h>
#include "../app_api.h"
#include "../tonecall_presets.h"
#include "../tonecall/tonecall_seq.h"
#include "tonecalledit_assets.h"   /* generated by gen_assets.py */

#ifndef APP_VERSION
#define APP_VERSION "dev"
#endif

#define LOOP_MS       10u
#define COMMIT_TICKS  80u     /* a multi-tap letter settles after 0.8 s */
#define ROWS          5u
#define VALUE_X       44u

enum { SCREEN_INDEX = 0, SCREEN_EDIT };
enum { F_NAME = 0, F_TYPE, F_CODE, F_COUNT };

static struct {
    const app_api_t *A;
    uint8_t *block;
    uint8_t sel, top, screen, field, held;
    uint8_t type, nameLen, codeLen, tapKey, tapCycle, tapTicks;
    bool running, dirty, changed, missing, digits, tapping;
    char name[TC_NAME_MAX + 1u];
    char code[TC_MAX_DIGITS + 1u];
} g;
#define A (g.A)

static uint8_t *rec(uint8_t i){ return g.block+4u+i*TC_REC_LEN; }

/* ---- record <-> draft ---- */
static void unpack(uint8_t i){
    const uint8_t *r=rec(i);
    uint8_t n=TC_NAME_MAX;
    while(n && r[TC_REC_NAME+n-1u]==' ') n--;
    for(uint8_t k=0;k<n;k++) g.name[k]=(char)r[TC_REC_NAME+k];
    g.name[n]='\0'; g.nameLen=n;
    uint8_t len=(uint8_t)(r[TC_REC_FORMAT]>>4);
    g.type=(uint8_t)(r[TC_REC_FORMAT]&15u);
    if(g.type>=TC_TYPE_COUNT) g.type=0;
    if(len>TC_MAX_DIGITS) len=0;
    for(uint8_t k=0;k<len;k++){
        const uint8_t b=r[TC_REC_CODE+(k>>1)];
        uint8_t d=(uint8_t)((k&1u)?(b&15u):(b>>4));
        if(d>9u) d=0;
        g.code[k]=(char)('0'+d);
    }
    g.code[len]='\0'; g.codeLen=len;
}

static void pack(uint8_t i){
    uint8_t *r=rec(i);
    for(uint8_t k=0;k<TC_NAME_MAX;k++) r[TC_REC_NAME+k]=(uint8_t)(k<g.nameLen?g.name[k]:' ');
    r[TC_REC_FORMAT]=(uint8_t)((g.codeLen<<4)|g.type);
    for(uint8_t k=0;k<4u;k++) r[TC_REC_CODE+k]=0;
    for(uint8_t k=0;k<g.codeLen;k++){
        const uint8_t d=(uint8_t)(g.code[k]-'0');
        r[TC_REC_CODE+(k>>1)]|=(uint8_t)((k&1u)?d:(d<<4));
    }
}

/* ---- drawing ---- */
static void invertLine(uint8_t line){ for(uint8_t x=0;x<128u;x++) A->fb[line][x]^=0xFFu; }

static void drawIndex(void){
    for(uint8_t r=0;r<ROWS;r++){
        const uint8_t i=(uint8_t)(g.top+r), line=(uint8_t)(1u+r);
        char s[TC_NAME_MAX+3u]; char *o=s;
        unpack(i);
        *o++=(char)('1'+i); *o++=' ';
        const char *label=g.codeLen?(g.nameLen?g.name:"-"):"EMPTY";
        while(*label) *o++=*label++;
        *o='\0';
        A->print_normal(s,1u,0u,line);
        if(g.codeLen) A->print_normal(g.code,(uint8_t)(127u-g.codeLen*7u),0u,line);
        if(i==g.sel) invertLine(line);
    }
    A->print_tiny("M EDIT  F CLEAR  EXIT SAVE",1u,50u,false,false);
}

static void drawEdit(void){
    static const char *const LABEL[F_COUNT]={"NAME","TYPE","CODE"};
    static const char *const HINT[F_COUNT]={"KEYS ABC  * ABC/123  F DEL","* NEXT  1-4 PICK","KEYS 0-9  F DEL"};
    char s[12]; char *o=s;
    o[0]='P'; o[1]='R'; o[2]='E'; o[3]='S'; o[4]='E'; o[5]='T'; o[6]=' '; o[7]=(char)('1'+g.sel); o[8]='\0';
    A->print_normal(s,0u,127u,0u);
    const char *value[F_COUNT]={g.name,tcTypeNames[g.type],g.code};
    for(uint8_t f=0;f<F_COUNT;f++){
        const uint8_t line=(uint8_t)(2u+f);
        A->print_normal(LABEL[f],2u,0u,line);
        A->print_normal(value[f],VALUE_X,0u,line);
        if(f==g.field){
            invertLine(line);
            if(f!=F_TYPE){                 /* insertion mark after the text */
                const uint8_t x=(uint8_t)(VALUE_X+(f==F_NAME?g.nameLen:g.codeLen)*7u);
                if(x<122u) for(uint8_t k=0;k<6u;k++) A->fb[line][x+k]&=0x7Fu;
            }
        }
    }
    if(g.field==F_NAME) A->print_inverse(g.digits?"123":"ABC",113u,6u,false,true,125u);
    A->print_tiny(HINT[g.field],1u,50u,false,false);
}

static void draw(void){
    A->display_clear(); A->status_clear();
    A->print_inverse("TC EDIT",2u,0u,true,true,30u);
    A->print_tiny(APP_VERSION,34u,1u,true,false);
    A->draw_battery();
    if(g.missing){
        A->print_normal("TONECALL NOT FOUND",0u,127u,2u);
        A->print_normal("INSTALL TONECALL",0u,127u,3u);
    } else if(g.screen==SCREEN_EDIT) drawEdit();
    else drawIndex();
    A->blit_status(); A->blit_full();
}

/* ---- name entry (multi-tap) ---- */
static void settle(void){ g.tapping=false; g.tapKey=APP_KEY_INVALID; g.tapCycle=0; g.tapTicks=0; }

static void nameKey(uint8_t key){
    if(g.digits){
        settle();
        if(g.nameLen<TC_NAME_MAX){ g.name[g.nameLen++]=(char)('0'+key); g.name[g.nameLen]='\0'; }
        return;
    }
    char chars[KEYMAP_STRIDE];
    A->asset_read((uint16_t)(KEYMAP+key*KEYMAP_STRIDE),chars,KEYMAP_STRIDE);
    if(g.tapping && g.tapKey==key){
        if(++g.tapCycle>=KEYMAP_STRIDE||!chars[g.tapCycle]) g.tapCycle=0;
        g.name[g.nameLen-1u]=chars[g.tapCycle];
    } else {
        settle();
        if(g.nameLen>=TC_NAME_MAX) return;
        g.name[g.nameLen++]=chars[0]; g.name[g.nameLen]='\0';
        g.tapping=true; g.tapKey=key;
    }
    g.tapTicks=0;
}

/* ---- keys ---- */
static void indexKey(uint8_t key){
    const int8_t d=A->nav_dir(key);
    if(d>0) g.sel=(uint8_t)(g.sel+1u<TC_PRESET_COUNT?g.sel+1u:0u);
    else if(d<0) g.sel=(uint8_t)(g.sel?g.sel-1u:TC_PRESET_COUNT-1u);
    else if(key==APP_KEY_MENU){ unpack(g.sel); g.field=F_NAME; g.digits=false; settle(); g.screen=SCREEN_EDIT; return; }
    else if(key==APP_KEY_F){ g.nameLen=0; g.codeLen=0; g.type=0; pack(g.sel); g.changed=true; return; }
    else if(key==APP_KEY_EXIT){
        if(g.changed) A->cfg_save(g.block,TC_PRESETS_LEN);
        g.running=false; return;
    }
    if(g.sel<g.top) g.top=g.sel;
    else if(g.sel>=g.top+ROWS) g.top=(uint8_t)(g.sel-ROWS+1u);
}

static void editKey(uint8_t key){
    const int8_t d=A->nav_dir(key);
    if(key!=g.tapKey||d||key>APP_KEY_9) settle();
    if(d>0) g.field=(uint8_t)(g.field+1u<F_COUNT?g.field+1u:0u);
    else if(d<0) g.field=(uint8_t)(g.field?g.field-1u:F_COUNT-1u);
    else if(key==APP_KEY_MENU){ pack(g.sel); g.changed=true; g.screen=SCREEN_INDEX; }
    else if(key==APP_KEY_EXIT) g.screen=SCREEN_INDEX;   /* the record is untouched */
    else if(g.field==F_NAME){
        if(key==APP_KEY_STAR) g.digits=!g.digits;
        else if(key==APP_KEY_F){ if(g.nameLen) g.name[--g.nameLen]='\0'; }
        else if(key<=APP_KEY_9) nameKey(key);
    } else if(g.field==F_TYPE){
        if(key==APP_KEY_STAR) g.type=(uint8_t)(g.type+1u<TC_TYPE_COUNT?g.type+1u:0u);
        else if(key>=APP_KEY_1 && key<=TC_TYPE_COUNT) g.type=(uint8_t)(key-1u);
    } else {
        if(key==APP_KEY_F){ if(g.codeLen) g.code[--g.codeLen]='\0'; }
        else if(key<=APP_KEY_9 && g.codeLen<TC_MAX_DIGITS){ g.code[g.codeLen++]=(char)('0'+key); g.code[g.codeLen]='\0'; }
    }
}

__attribute__((section(".text.entry"),used))
void app_main(const app_api_t *api){
    uint8_t block[TC_PRESETS_LEN];
    uint32_t magic=0;
    A=api; g.block=block;
    g.held=APP_KEY_INVALID; g.tapKey=APP_KEY_INVALID;
    api->cfg_load(block,TC_PRESETS_LEN);
    for(uint8_t k=0;k<4u;k++) magic|=(uint32_t)block[k]<<(8u*k);
    g.missing=magic!=TC_PRESETS_MAGIC;
    g.running=true; g.dirty=true;
    api->backlight_on();

    while(g.running){
        if(g.dirty){ g.dirty=false; draw(); }
        const uint8_t key=api->get_key();
        if(key==APP_KEY_SAVER||key==APP_KEY_WAKE){ g.held=APP_KEY_INVALID; g.dirty=true; }
        else if(key!=g.held){
            g.held=key;
            if(key!=APP_KEY_INVALID){
                api->backlight_on();
                if(g.missing){ if(key==APP_KEY_EXIT) g.running=false; }
                else if(g.screen==SCREEN_EDIT) editKey(key);
                else indexKey(key);
                g.dirty=true;
            }
        }
        if(g.tapping && ++g.tapTicks>=COMMIT_TICKS){ settle(); g.dirty=true; }
        api->battery_sample(); api->delay_ms(LOOP_MS); api->backlight_update();
    }
}
